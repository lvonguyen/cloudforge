#!/usr/bin/env node
/**
 * seed-resources.mjs — Generate SQL seed file for the resources table
 *
 * Reads testdata/seed/resources.json and generates a SQL file compatible with
 * the resources table (migration 006). Uses batched INSERT for fast loading.
 *
 * Usage:
 *   node scripts/seed-resources.mjs --in testdata/seed/ --out testdata/seed/seed-resources.sql
 *   psql "$DATABASE_URL" < testdata/seed/seed-resources.sql
 *
 * Flags:
 *   --in DIR     Input directory (default: testdata/seed/)
 *   --out FILE   Output SQL file (default: testdata/seed/seed-resources.sql)
 *   --truncate   Add TRUNCATE before INSERT (default: true, use --no-truncate to skip)
 */

import { readFileSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';

const args = process.argv.slice(2);
const getArg = (name) => { const i = args.indexOf(name); return i !== -1 ? args[i + 1] : undefined; };
const hasFlag = (name) => args.includes(name);

const IN_DIR = resolve(getArg('--in') ?? 'testdata/seed');
const OUT_FILE = resolve(getArg('--out') ?? join(IN_DIR, 'seed-resources.sql'));
const TRUNCATE = !hasFlag('--no-truncate');
const BATCH_SIZE = 100;

const log = (msg) => process.stderr.write(`[+] ${msg}\n`);

function esc(val) {
  if (val === null || val === undefined) return 'NULL';
  if (typeof val === 'boolean') return val ? 'TRUE' : 'FALSE';
  if (typeof val === 'number') return String(val);
  const s = String(val).replace(/'/g, "''");
  return `'${s}'`;
}

// ── Main ─────────────────────────────────────────────────────────────────────

const inputFile = join(IN_DIR, 'resources.json');
log(`Reading ${inputFile}...`);
const resources = JSON.parse(readFileSync(inputFile, 'utf-8'));
log(`Loaded ${resources.length} resources`);

const lines = [];
lines.push('-- Generated by scripts/seed-resources.mjs');
lines.push(`-- ${resources.length} resources from aegis-seed pipeline`);
lines.push(`-- Generated: ${new Date().toISOString()}`);
lines.push('');
lines.push('BEGIN;');
lines.push('');

if (TRUNCATE) {
  lines.push('-- Clear existing resources');
  lines.push('TRUNCATE resources CASCADE;');
  lines.push('');
}

// ── Resources ────────────────────────────────────────────────────────────────

const COLS = [
  'id', 'name', 'resource_type', 'region', 'account_id',
  'cloud_provider', 'account_name', 'resource_arn', 'tenant_id',
];

function resourceToValues(r) {
  return [
    esc(r.resource_id),
    esc(r.resource_name),
    esc(r.resource_type),
    esc(r.region),
    esc(r.account_id),
    esc(r.cloud_provider),
    esc(r.account_name),
    esc(r.resource_arn),
    esc('default'),
  ].join(', ');
}

lines.push(`-- ${resources.length} resources in batches of ${BATCH_SIZE}`);

for (let i = 0; i < resources.length; i += BATCH_SIZE) {
  const batch = resources.slice(i, i + BATCH_SIZE);
  lines.push(`INSERT INTO resources (${COLS.join(', ')}) VALUES`);
  const rows = batch.map(r => `  (${resourceToValues(r)})`);
  lines.push(rows.join(',\n'));
  lines.push('ON CONFLICT (id) DO NOTHING;');
  lines.push('');
}

lines.push('COMMIT;');
lines.push('');
lines.push(`-- Summary: ${resources.length} resources`);

const sql = lines.join('\n');
writeFileSync(OUT_FILE, sql);

const sizeMB = (Buffer.byteLength(sql) / 1024 / 1024).toFixed(1);
log(`Wrote ${OUT_FILE} (${sizeMB} MB)`);
log(`  ${resources.length} resources`);
log(`  Load with: psql "$DATABASE_URL" < ${OUT_FILE}`);
